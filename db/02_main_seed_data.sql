-- 用途：db/01_main_schema.sql 只建表结构，本文件补齐站点跑起来
--       所必需的基础数据。全新搭建时两个文件都要导入，缺本文件会导致：
--         · 发布页地区/类别下拉为空 → 无法发布任何信息
--         · 后台「参数配置」页空白 → 无法调整任何参数
--           （settings 页只做 UPDATE 不做 INSERT，表里没有行就什么都改不了）
